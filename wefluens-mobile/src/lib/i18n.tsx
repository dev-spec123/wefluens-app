const tables: Record<Lang, Dict> = { en, zh, es };

export type L10nKey = keyof typeof en;

const STORAGE_KEY = 'wefluens.language';

// Module-level mirror of the active language so non-React code (e.g. lib/api.ts)
// can read the current language without a hook. Kept in sync by LanguageProvider.
let currentLang: Lang = 'en';
export function getCurrentLang(): Lang {
  return currentLang;
}

interface I18nContextValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: L10nKey | string) => string;
  LANGUAGES: typeof LANGUAGES;
}

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

function deviceDefault(): Lang {
  const code = Localization.getLocales?.()[0]?.languageCode ?? 'en';
  if (code === 'zh') return 'zh';
  if (code === 'es') return 'es';
  return 'en';
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');

  useEffect(() => {
    (async () => {
      const stored = (await AsyncStorage.getItem(STORAGE_KEY)) as Lang | null;
      const resolved = stored ?? deviceDefault();
      currentLang = resolved;
      setLangState(resolved);
    })();
  }, []);

  const setLang = useCallback((l: Lang) => {
    currentLang = l;
    setLangState(l);
    AsyncStorage.setItem(STORAGE_KEY, l).catch(() => {});
  }, []);

  const t = useCallback(
    (key: string) => tables[lang][key] ?? tables.en[key] ?? key,
    [lang],
  );

  return <I18nContext.Provider value={{ lang, setLang, t, LANGUAGES }}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within a LanguageProvider');
  return ctx;
}
